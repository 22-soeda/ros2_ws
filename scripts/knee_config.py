#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""膝 4 節リンク（サーボ角 <-> 膝関節角）の寸法・分岐・原点。

``knee_fourbar.py`` が読む値はこのファイルにだけ置く。
``leg_config.py`` と同じ約束で、確定していない値はここを書き換えるだけで済むように
本体には一切埋め込まない。単位は長さ mm、角度 deg（``knee_fourbar`` 側で rad に直す）。

記号は ``docs/膝4節リンク導出.tex`` (KN-1)〜(KN-11) に対応する。同文書は大腿座標系
Σ_t の点 (O, P0, Q0) からリンク長を作る書き方だが、ここでは膝軸を原点・O2 を +x 上に
置いた「絶対角」の形で持つ。両者は原点と基準角のずれだけの違いで、そのずれは §4 の
THETA4_ZERO / PHI0 が吸収する。対応は

    r1 = g（地節）, r2 = a（クランク）, r3 = b（カプラ）, r4 = c（ロッカー）
    θ2 = q4 + 定数,  θ4 = ψ = ψ0 + θ4_doc

座標系（矢状面。膝軸まわりの回転面をそのまま 2 次元で見る）

    O4 = (0, 0)                        膝軸。原点
    O2 = (R1, 0)                       モータ軸
    A  = O2 + R2·(cos θ2, sin θ2)      クランク先端のピン
    B  = O4 + R4·(cos θ4, sin θ4)      ロッカー側のピン
    拘束は |B − A| = R3 の 1 本だけ。角度はすべて +x から反時計回り [0, 2π)。
"""

from __future__ import annotations

__all__ = [
    "R1", "R2", "R3", "R4",
    "BETA", "EPS",
    "THETA4_ZERO_DEG", "SIGMA_JOINT",
    "SERVO_ID", "SERVO_PORT", "PHI0_DEG", "SIGMA_MOTOR", "GEAR",
    "JOINT_LIMIT_DEG", "MOTOR_SWEEP_DEG", "SIDES",
]

#: 左右の並び。左右で値が変わるものはこの順の dict で持つ。
SIDES = ("right", "left")

# ---------------------------------------------------------------------------
# リンク長                                                          [mm]
# ---------------------------------------------------------------------------
#: 地節（大腿）O4 -> O2。膝軸とモータ軸の距離
R1 = 20.0
#: クランク（入力・モータ）
R2 = 45.0
#: カプラ（連結ロッド）
R3 = 35.0
#: ロッカー（出力・膝ジョイント側のレバー）
R4 = 20.0

# ---------------------------------------------------------------------------
# 枝（円と円の 2 交点のどちらに組んであるか）
# ---------------------------------------------------------------------------
# β は順変換 (KN-5)、ε は逆変換 (KN-7) の arccos に付く符号。**機体を組んだ時点で
# 決まる定数**で、動作中に切り替わることはない。実機で 1 姿勢だけ (θ2, θ4) を実測して
# knee_fourbar.branches_from_pose() に通せば確定する。
#
# TODO(実機): 1 姿勢の実測で確定する。下は既存 MATLAB 実装と同じ側という暫定値。
BETA = -1
EPS = +1

# ---------------------------------------------------------------------------
# 膝関節角 <-> ロッカー角（脚 IK との繋ぎこみ）
# ---------------------------------------------------------------------------
#     θ4_rocker = SIGMA_JOINT · θ4_joint + THETA4_ZERO
#
# θ4_joint は脚 IK が出す膝関節角（伸展 0・屈曲 +）、θ4_rocker はこの文書のロッカー
# 絶対角。下腿とロッカーの相対角なので、CAD か実測でしか決まらない。
#
# **確定値**。脚が伸び切った姿勢（T ポーズ）でロッカーが 89.3 deg を向く。
THETA4_ZERO_DEG = 89.3

#: 膝の曲がる向き ±1。
#: **枝 (BETA, EPS) と THETA4_ZERO_DEG から一意に決まる**ので、これは選択の余地がない。
#: σ = -1 は屈曲 60.3 deg (θ4 = 28.96 deg) で死点に当たり、そこで伝達比が 0.03 まで
#: 落ちてサーボが膝を動かせなくなる。設計可動域 0-150 deg に届くのは +1 だけ。
#: knee_selftest / test_knee_fourbar がこの一意性を毎回検算する。
SIGMA_JOINT = +1

# ---------------------------------------------------------------------------
# クランク角 -> サーボ指令（導出 (4) 式）
# ---------------------------------------------------------------------------
#     motor_cmd = PHI0 + SIGMA_MOTOR · GEAR · θ2
#
# **左右で別々に持つ。** 膝サーボは左右とも ID 4 で、どちらのバスに繋がっているかが
# 左右を決める（/dev/feetech_left の ID4 = 左膝、/dev/feetech_right の ID4 = 右膝）。
# 4 節リンクの幾何そのもの（R1-R4, BETA, EPS, THETA4_ZERO_DEG, SIGMA_JOINT）は左右共通
# だが、**サーボの原点は取り付けごとの実測値なので左右で違う**。実際
# feetech_servo/config/servo_home.yaml の ID4 は左 2095 / 右 1835 で 22.85 deg ずれている。
# σ_m も鏡像取り付けなら左右で反転しうるので、同じく左右別に持つ。

#: 膝サーボの ID。左右とも同じで、バスが左右を決める。
SERVO_ID = 4

#: 左右のバス（udev の固定名。ttyACM の番号は入れ替わる実績があるので使わない）。
SERVO_PORT = {"right": "/dev/feetech_right", "left": "/dev/feetech_left"}

#: **脚が伸び切った姿勢でのサーボ生カウント。** これが φ0 の実体。
#:
#: 出どころは feetech_servo/config/servo_home.yaml の ID4（各サーボに対応づけた初期位置）で、
#: feetech_calibrate_home が書くファイル。**あちらが一次資料**なので、原点を取り直したら
#: ここも写し直す（serve_knee3d.py は yaml を直接読み、この値と食い違ったら警告を出す）。
#:
#: φ0 は σ_m と n に依る派生量なので定数で持たず、phi0_from_home() で作る。
SERVO_HOME_COUNT = {"right": 1835, "left": 2095}

#: サーボ 1 回転のカウント数（0-4095 = 0-360 deg）。
SERVO_COUNTS = 4096

# σ_m: **左右とも実機確認済み（2026-08-28）**。左 +1 / 右 -1。
#      右脚は ID4 の回転方向が左と逆に組まれている（左右で鏡像になる取り付け）。
#      **左右で違うのはこれだけ**で、枝 BETA/EPS も θ4_zero も左右共通。
# n  : 直結とみなした暫定値。実機で振り幅が合わなければ見直す。
# φ0 : 定数では持たない。SERVO_HOME_COUNT から phi0_from_home() が作る。
#      PHI0_DEG は「home 以外で原点を決めたい」ときの上書き用に残してある。
PHI0_DEG = {"right": 0.0, "left": 0.0}      #: 上書き用。既定は home から作る [deg]
SIGMA_MOTOR = {"right": -1, "left": +1}     #: サーボの回転方向 σ_m  ±1（実機で確認）
GEAR = {"right": 1.0, "left": 1.0}          #: ギア比 n（サーボ角 / クランク角）

# ---------------------------------------------------------------------------
# 可動域（設計値）                                                  [deg]
# ---------------------------------------------------------------------------
#: 膝関節角の設計可動域。leg_config.JOINT_LIMITS_DEG["knee"] と揃える。
JOINT_LIMIT_DEG = (0.0, 120.0)

#: 検算・作図で掃く θ2 の範囲。組める範囲 [70.53, 289.47] の内側に取る。
MOTOR_SWEEP_DEG = (160.0, 270.0)
