"""片脚 FK/IK の寸法パラメータ。

``leg_ik.py`` が読む値はこのファイルにだけ置く。CAD が変わったらここだけを
書き換えれば ``leg_ik.py`` には一切手を入れなくてよい。

単位は長さ mm、角度 deg（``leg_ik`` 側で rad に変換する）。

**座標系は機体座標 Σ_B（x = 前, y = 左, z = 上）**。C++ 側の
``src/roboone_kinematics/include/roboone_kinematics/leg_config.hpp`` と同じ座標系・
同じ値で、写すときの読み替えは無い（2026-09-14 に文書の Σ_0 = x 右 / y 前 から
書き直した）。値は右脚のもので、左脚は y を反転して作る。
"""

from __future__ import annotations

__all__ = [
    "L3", "L4", "L5", "L6", "A3_Y", "A4_Y", "B_THIGH",
    "HIP_X", "HIP_Y", "HIP_Z", "SIGMA", "P6",
    "AXIS_FLIP", "AXIS_FLIP_LEFT", "JOINT_LIMITS_DEG",
]

# ---------------------------------------------------------------------------
# リンク長（上下方向の成分）                                        [mm]
# ---------------------------------------------------------------------------
L3 = 142.5      # 大腿の高さ成分: 股中心 o3 -> 膝軸 o4
L4 = 141.021    # 下腿の高さ成分: 膝軸 o4 -> 足首ピッチ軸 o5
L5 = 7.924      # 足首 2 軸の高さオフセット o5 -> o6（ピッチ軸 -> ロール軸）
L6 = 8.5        # 足首ロール軸 o6 -> 足裏中心

# ---------------------------------------------------------------------------
# 左右方向（膝軸 = y）のオフセット
# ---------------------------------------------------------------------------
# p3 = (B_THIGH, A3_Y, -L3)   股中心 o3 -> 膝軸 o4   (Σ_3)
# p4 = (0,       A4_Y, -L4)   膝軸 o4   -> 足首軸 o5 (Σ_4)
#
# y は膝軸 (J4) の方向なので、o4 を膝軸に沿って滑らせても関節は変わらない。
# つまり A3_Y と A4_Y は和 a = A3_Y + A4_Y だけが幾何に効き、分け方は結果に
# 影響しない。CAD の実測値をそのまま入れてよい。
# 実機は +14.642 / -14.642（和 0）。leg_config.hpp の P3_Y / P4_Y と同じ。
A3_Y = 14.642
A4_Y = -14.642

# ---------------------------------------------------------------------------
# その他のオフセット
# ---------------------------------------------------------------------------
#: 大腿の前後（x）オフセット。膝軸が股中心の真下から前後にずれる量。
#: 0 でなくても ℓ3' = hypot(ℓ3, b)、θ4' = θ4 + atan2(b, ℓ3) で吸収できる。
B_THIGH = 0.0

#: ボディ原点 -> 股中心 o3 のベクトル p0（右脚）。左脚は y を反転する。
#: 実測は「前後 0 / 左右 89.3 / 上下 0」。右脚は y = -89.3。
HIP_X = 0.0
HIP_Y = -89.3
HIP_Z = 0.0

#: o6 -> 足先基準点 p6 (Σ_6)。None なら (0, 0, -L6) を使う。
#: 足裏の接地基準点を足首軸の真下から前後・左右にずらすならここで指定する。
P6 = None

#: 膝の分岐 σ = ±1。arccos は θ4 と -θ4 を区別しないので機体で 1 つに固定する。
#: +1 で θ4 > 0 の側 = 人型（膝が前に出る）。leg_config.hpp の KNEE_FORWARD と同じ。
#: AXIS_FLIP["knee"] = 1 のときは ik() が返す θ4 の符号が σ と逆になる。
SIGMA = +1

# ---------------------------------------------------------------------------
# 各軸の回転方向
# ---------------------------------------------------------------------------
# 0 = Σ_B の正軸まわりの右ねじが正 / 1 = 逆（正負を入れ替える）
#
# 実機の軸の向きが逆になっている関節をここで 1 にする。
# fk() に渡す角も ik() が返す角も、この符号を適用したあとの値になる。
# 幾何そのものは変わらないので、膝がどちら側に曲がるかは SIGMA が決める
# （AXIS_FLIP["knee"] を 1 にしても曲がる向きは変わらず、報告される符号だけ反転する）。
AXIS_FLIP = {
    "hip_pitch":   0,
    "hip_roll":    0,
    "hip_yaw":     0,
    "knee":        0,
    "ankle_pitch": 0,
    "ankle_roll":  0,
}

#: 左脚の回転方向。左右でサーボの向きが鏡像になっている場合はここに別の表を書く。
#: None なら AXIS_FLIP と同じものを使う。
AXIS_FLIP_LEFT = None

# ---------------------------------------------------------------------------
# 可動域（仮置き。自己検算で使う範囲）                              [deg]
# ---------------------------------------------------------------------------
# ※ AXIS_FLIP を適用する前の内部角での範囲。
#: knee は曲げ量（伸展 0・屈曲 +）。実際の θ4 は σ * 曲げ量 - atan2(b, ℓ3)。
JOINT_LIMITS_DEG = {
    "hip_pitch":   (-90.0, 90.0),
    "hip_roll":    (-90.0, 90.0),
    "hip_yaw":     (-90.0, 90.0),
    "knee":        (0.0, 150.0),
    "ankle_pitch": (-60.0, 60.0),
    "ankle_roll":  (-60.0, 60.0),
}
