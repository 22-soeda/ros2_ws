// 片脚 FK/IK の寸法パラメータ。
//
// leg_kinematics.hpp が読む値はこのファイルにだけ置く。
// CAD が変わったらここだけを書き換えれば leg_kinematics.hpp には手を入れなくてよい。
//
// 単位は長さ mm、角度 deg（内部では rad に直す）。
//
// ===========================================================================
// 座標系 Σ_B（機体座標。walk_core と共通）
// ===========================================================================
//   x = 前, y = 左, z = 上   （REP-103。walk_core/engine.py と同じ取り方）
//   原点はボディ原点（骨盤）。ゼロ姿勢で脚は真下に伸び、足裏は水平。
//
// 文書 docs/脚IK導出.tex の Σ_0 は x = 右, y = 前, z = 上 なので、この
// ファイルの値とは z まわりに 90° ずれている。読み替えは leg_kinematics.hpp の
// 「座標系」節に 1 か所だけ書いてあり、CAD の値はここへ Σ_B のまま入れてよい。
//
// **値は右脚 (Side::RIGHT) の Σ_B 成分**。左脚は y 成分を反転して作る（左右対称）。
#ifndef ROBOONE_KINEMATICS__LEG_CONFIG_HPP_
#define ROBOONE_KINEMATICS__LEG_CONFIG_HPP_

namespace roboone_kinematics::config
{

// ---------------------------------------------------------------------------
// リンク長（上下方向の成分。文書 表 1 の ℓ_k）                        [mm]
// ---------------------------------------------------------------------------
inline constexpr double L3 = 142.5;     // 股中心 o3 -> 膝軸 o4（大腿）
inline constexpr double L4 = 141.021;   // 膝軸 o4 -> 足首ロール軸 o5（下腿）
inline constexpr double L5 = 7.924;     // 足首 2 軸のオフセット o5 -> o6（ℓ4 > ℓ5 が必要）
inline constexpr double L6 = 8.5;       // 足首ピッチ軸 o6 -> 足裏中心

// ---------------------------------------------------------------------------
// 左右方向（膝軸 = y_B）のオフセット                                   [mm]
// ---------------------------------------------------------------------------
// p3 = (P3_X, P3_Y, -L3)   股中心 o3 -> 膝軸 o4   (Σ_3)
// p4 = (0,    P4_Y, -L4)   膝軸 o4   -> 足首軸 o5 (Σ_4)
//
// y は膝軸 (J4) の方向なので、o4 を膝軸に沿って滑らせても関節角は変わらない。
// つまり P3_Y と P4_Y は **和だけ** が幾何に効き、分け方は FK/IK の結果に影響
// しない（leg_selftest の「分け方の不変性」で確認している）。CAD の実測値を
// そのまま入れてよく、この 2 つの符号を取り違えても和が同じなら結果は同じ。
//
// 実機は +14.642 / -14.642 で和 = 0、つまり o5 は o3 の真下に来る。
inline constexpr double P3_Y = 14.642;
inline constexpr double P4_Y = -14.642;

// 大腿の前後オフセット（膝軸が股中心の真下から前後にずれる量）。
// 0 でなくても ℓ3' = hypot(L3, P3_X)、θ4' = θ4 + atan2(P3_X, L3) で吸収できる。
// ※ 下腿側 (p4) の前後オフセットは解析解の前提から 0 でなければならない。
inline constexpr double P3_X = 0.0;

// ---------------------------------------------------------------------------
// 股中心とつま先
// ---------------------------------------------------------------------------
// ボディ原点 -> 股中心 o3 のベクトル p0 (Σ_B)。**右脚の値**なので HIP_Y は負。
// 左脚は y を反転する（股間隔は 2 x 89.3 = 178.6 mm）。
// 実測は「前後 0 / 左右 89.3 / 上下 0」。ボディ原点は股 3 軸の交点と同じ高さで、
// 左右中央にある。したがって立位の骨盤高さの上限 = 脚全長 299.945 mm。
// TODO: walk_core の foot_spacing = 80 mm（足を ±40 mm）は股間隔 ±89.3 mm と
//       食い違うので、どちらかを合わせる。
inline constexpr double HIP_X = 0.0;
inline constexpr double HIP_Y = -89.3;
inline constexpr double HIP_Z = 0.0;

// o6 -> 足裏中心 p6 (Σ_6)。接地基準点を足首軸の真下からずらすならここ。
inline constexpr double P6_X = 0.0;
inline constexpr double P6_Y = 0.0;
inline constexpr double P6_Z = -L6;

// ---------------------------------------------------------------------------
// 膝の曲がる向き
// ---------------------------------------------------------------------------
// arccos は θ4 と -θ4 を区別しないので、機体の組み方でどちらか一方に固定する。
//   +1 : 人型。膝が前に出る（θ4 > 0 で足先が後ろへ振れる）
//   -1 : 逆関節（鳥型）
// 実機は人型なので +1。AXIS_FLIP[KNEE] を 1 にしても曲がる向きは変わらず、
// 報告される符号だけが反転する。
inline constexpr int KNEE_FORWARD = +1;

// ---------------------------------------------------------------------------
// 各軸の回転方向
// ---------------------------------------------------------------------------
// 0 = Σ_B の正軸まわりの右ねじが正 / 1 = 逆（正負を入れ替える）
// 並びは {J1, J2, J3, J4, J5, J6}（下の Joint enum と同じ）。
//
// 実機のサーボの向きが Σ_B の取り方と逆になっている関節をここで 1 にする。
// fk() に渡す角も ik() が返す角も、この符号を適用したあとの値になる。
//
// TODO(実機): 1 軸ずつ正方向に少し動かして向きを確かめる。
inline constexpr int AXIS_FLIP[6]      = {0, 0, 0, 0, 0, 0};
// 左脚。左右でサーボの向きが鏡像ならここに別の表を書き、SEPARATE を true に。
// ※ 関節角そのものは左右とも Σ_B（機体共通）で定義してあるので、鏡像に
//    なるのはサーボの回り方だけ。幾何の左右対称は makeLegParams が扱う。
inline constexpr bool AXIS_FLIP_LEFT_SEPARATE = false;
inline constexpr int AXIS_FLIP_LEFT[6] = {0, 0, 0, 0, 0, 0};

// ---------------------------------------------------------------------------
// 可動域（仮置き。自己検算で使う範囲）                                 [deg]
// ---------------------------------------------------------------------------
// ※ Σ_B の関節角で、AXIS_FLIP を適用する前の値。
//    KNEE は「曲げ量」で、KNEE_FORWARD = +1 なら θ4 そのもの。
// TODO: サーボのリミット（feetech_servo/config/servo_limits.yaml）と突き合わせる。
inline constexpr double JOINT_LIMIT_LO_DEG[6] = {-60.0, -60.0, -60.0,   0.0, -60.0, -60.0};
inline constexpr double JOINT_LIMIT_HI_DEG[6] = { 60.0,  60.0,  60.0, 150.0,  60.0,  60.0};

}  // namespace roboone_kinematics::config

#endif  // ROBOONE_KINEMATICS__LEG_CONFIG_HPP_
