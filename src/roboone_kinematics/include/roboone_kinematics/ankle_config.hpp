// 足首パラレルリンク FK/IK の寸法パラメータ。
//
// ankle_parallel.hpp が読む値はこのファイルにだけ置く。CAD が変わったらここだけを
// 書き換えれば ankle_parallel.hpp には手を入れなくてよい（leg_config.hpp と同じ約束）。
//
// 出典: 「足首パラレルリンク：関節角 ↔ サーボ角 変換の実装仕様」§3（CAD 実測）。
// 単位は長さ mm、角度 deg（内部では rad に直す）。
//
// ---------------------------------------------------------------------------
// 座標系  REP-103 (x = 前, y = 左, z = 上)。leg_config.hpp と共通。
// ---------------------------------------------------------------------------
//   Σ_s : 原点 o5（足首**ピッチ**軸。上側ピボット）。姿勢は膝の後の Σ_4 と同じ。
//         下腿に固定された量（a_i0, クランク軸）はここで定数になる。
//   Σ_6 : 原点 o6（足首**ロール**軸。下側ピボット）。足板に固定された量（b_i）はここで定数。
//   o5 -> o6 = (0, 0, -ℓ5)
//
//   R5 = Ry(θ5)  足首ピッチ（左右軸まわり）。上側ピボット（腰に近い方）
//   R6 = Rx(θ6)  足首ロール（前後軸まわり）。下側ピボット（足に近い方）
//
// ★2026-09-14 に上下の軸を入れ替えた。仕様書 §1 は「上側がロール」としていたが、
//   実機はユニバーサルジョイントの上側ピボットが y まわり（ピッチ）、下側が x まわり
//   （ロール）。leg_kinematics.hpp の Joint enum（ANKLE_PITCH = θ5 / ANKLE_ROLL = θ6）
//   とサーボ名の「足首ピッチ / 足首ロール」は、これで軸の向きとも一致する。
//   仕様書 §8 の数値（中立クランク角・可動域・線形近似）はこの入れ替えで変わって
//   いるので、下の値と ankle_selftest の期待値は実装で取り直したもの。
//
// 添え字 i = 0,1 が仕様の鎖 i = 1,2 に対応する（C++ 側は 0 始まり）。
//   鎖 1 = 下側サーボ（取付高さ 73mm）＋短ロッド（80mm）
//   鎖 2 = 上側サーボ（取付高さ 108mm）＋長ロッド（115mm）
#ifndef ROBOONE_KINEMATICS__ANKLE_CONFIG_HPP_
#define ROBOONE_KINEMATICS__ANKLE_CONFIG_HPP_

namespace roboone_kinematics::ankle_config
{

// ---------------------------------------------------------------------------
// クランク側（下腿に固定。Σ_s）                                        [mm]
// ---------------------------------------------------------------------------
// a_i0 : クランク軸 O_i から o5 へ向かうベクトル。
//        クランク軸の位置そのものが要るときは O_i = -a_i0。
//        s = +1/-1 が左右の脚。**同じ脚の中で 2 個のサーボの y 符号は逆**で、
//        下腿の左右に分かれて付く（仕様 §3「符号について」）。
//        これを同符号にすると判別式が負になり、そもそも機構が成立しない。
inline constexpr double A0[2][3] = {
  {-12.5, -27.5, -73.0},    // 鎖 1（下側）。y は s 倍する
  {-12.5, +27.5, -108.0},   // 鎖 2（上側）
};
//! A0 の y に掛ける符号（左右で反転する成分）。x, z は左右共通。
inline constexpr int A0_Y_SIDE_SIGN = 1;

// r_i1 : クランク半径。
inline constexpr double CRANK_RADIUS[2] = {18.0, 18.0};

// クランク軸は左右軸（y）に平行（仕様 §2 の A1）。回転円は x-z 平面内にあり、
// 円内の基準方向 û_i（q_i = 0 の向き）は +x に取る。
//   û = (1,0,0)、v̂ = (0,0,1)、ê = û × v̂ = (0,-1,0)
// A1 が崩れて軸が傾いていたら、ここを CAD の実測値に置き換えれば同じ手順で解ける
// （仕様 §7 の一般形）。ただし ankle_parallel.hpp の閉形式は û=x̂ / v̂=ẑ を前提に
// 展開してあるので、傾ける場合は一般形の実装に差し替えること。
inline constexpr double CRANK_AXIS[3] = {0.0, -1.0, 0.0};
inline constexpr double CRANK_REF_DIR[3] = {1.0, 0.0, 0.0};

// ---------------------------------------------------------------------------
// 足側（足板に固定。Σ_6、原点は o6）                                   [mm]
// ---------------------------------------------------------------------------
// b_i : ロッドの足側ボール中心。**各サーボは自分と同じ側のボールを引く**ので、
//       a_i0 と b_i の y 符号は鎖ごとに逆になる（仕様 §3）。
inline constexpr double FOOT_BALL[2][3] = {
  {14.5, +26.5, 2.5},   // 鎖 1。y は s 倍する
  {14.5, -26.5, 2.5},   // 鎖 2
};
inline constexpr int FOOT_BALL_Y_SIDE_SIGN = 1;

// ---------------------------------------------------------------------------
// 足裏を基準にしたボール軸の位置（実機実測 2026-08-28）
// ---------------------------------------------------------------------------
// b_i は o6 が原点なので、実機でノギスを当てられる「足裏から」の値とは基準が違う。
// 突き合わせるには leg_config.hpp の p6（o6 -> 足裏中心）を足す必要がある。
//
//   高さ  = b_i.z - P6_Z = b_i.z + L6 = 2.5 + 8.5 = 11.0 mm
//   前後  = b_i.x - P6_X = 14.5 - 0   = 14.5 mm
//
// ★足首ピッチ軸 o6 は足裏中心の真上にある（P6_X = P6_Y = 0）。前後に 14.5 mm
//   ずれているのは o6 ではなく**ロッドを受ける足側のボール軸のほう**。
//   ここを取り違えると P6_X に 14.5 を入れてしまい、足先位置が 14.5 mm ずれる。
//
// ankle_selftest が下の値と実際の b_i・p6 を突き合わせる。CAD や実測を更新したら
// b_i / L6 と一緒にここも直すこと。
inline constexpr double BALL_HEIGHT_ABOVE_SOLE = 11.0;   //!< 足裏 -> ボール軸 [mm]
inline constexpr double BALL_X_FROM_SOLE_CENTER = 14.5;  //!< 足裏中心 -> ボール軸 [mm]

// ---------------------------------------------------------------------------
// ロッド                                                                [mm]
// ---------------------------------------------------------------------------
// r_i2 : ボール中心間距離。ターンバックルなら公称値と調整範囲を確認する（仕様 §9-7）。
inline constexpr double ROD_LENGTH[2] = {80.0, 115.0};

// ---------------------------------------------------------------------------
// 足首 2 軸の高さオフセット ℓ5                                          [mm]
// ---------------------------------------------------------------------------
// leg_config.hpp の L5 と同じ量なので二重定義せず、ankle_parallel.hpp が
// config::L5 を読む。脚 IK 側の ℓ5 と食い違っていると FK と IK で足先位置がずれる。
// ankle_selftest の数値の期待値（中立クランク角・可動域・∂q/∂θ）はこの値で
// 取ったもの。L5 を変えたら期待値は取り直す（selftest は寸法に依る照合を飛ばす）。
inline constexpr double L5_REF = 7.924;

// ---------------------------------------------------------------------------
// 組み立ての枝                                                        [±1]
// ---------------------------------------------------------------------------
// ε_i : 逆変換（仕様 §4.4）。円と球の交点は 2 つあるが、どちらに組むかは機体を
//       組んだ時点で決まり、動作中に切り替わることはない。
//       中立姿勢での 2 解（ℓ5 = 7.924）:  鎖1 = -0.149° / -176.930°、鎖2 = +1.445° / -179.425°
//       既定 +1 は「中立でクランクが +x 方向をほぼ向く」側。
//       実機でクランクが後ろを向いていたら -1 にする（仕様 §9-3）。
inline constexpr int BRANCH_EPS[2] = {+1, +1};

// β_i : 順変換（仕様 §5.1）。中立で Θ_i(0) = 0 になる側。
//       BRANCH_FROM_NEUTRAL = true なら finalize() が自動で選ぶので、寸法を
//       差し替えても壊れない。下の値はその結果（β1 = -1, β2 = -1）。
inline constexpr bool BRANCH_FROM_NEUTRAL = true;
inline constexpr int BRANCH_BETA[2] = {-1, -1};

// ---------------------------------------------------------------------------
// サーボ指令への換算（仕様 §4.5）
// ---------------------------------------------------------------------------
//   φ_i = φ_i,home + σ_i n_i (q_i - q_i,neutral)
//
// ★原点は **T ポーズ**で取ってある（実機 2026-08-28）。
//   「脚がちょうど真上に伸びる」ように足首のサーボを回して合わせた位置が、
//   feetech_servo/config/servo_home.yaml の home。つまり
//
//       サーボ実測 = home  ⟺  (θ5, θ6) = (0, 0)  ⟺  q_i = q_i,neutral
//
//   で、q_i,neutral は 0 ではなく (-0.390°, +1.202°)。仕様 §4.5 の φ_i0 を
//   そのまま定数で持つと、この 0.39° / 1.20° をどこかで足し忘れる。そこで
//   finalize() が中立姿勢の逆変換を 1 回解いて q_i,neutral を自動で入れ、
//   config には「T ポーズでのサーボ値」だけを置く。servo_home.yaml の原点を
//   0 deg と読むなら 0 のままでよい。
inline constexpr double SERVO_HOME_DEG[2] = {0.0, 0.0};

// σ_i : サーボの回転方向。**2 個のサーボは下腿の反対側に付くので出力軸の向きが
//       逆になり、σ_1 ≠ σ_2 になる**（仕様 §4.5 の予告どおり）。
//
// 左右で逆になる鎖が入れ替わるので、**脚ごとに持つ**。行が脚、列が鎖:
//
//            鎖 0 (ID6・短 80mm)   鎖 1 (ID5・長 115mm)
//   左脚          -1                     +1
//   右脚          +1                     -1
//
// 左右が鏡像なので、反転する側が入れ替わるのは幾何のとおり。
// 2026-08-28 実機で確認（手で足首を動かしたときの向きで判定）。
//
// ★T ポーズでは φ = φ_home なので σ に関わらず同じ値になる。**原点合わせでは
//   σ の誤りは見つからない。** 動かしたときの向きでしか分からないので、
//   軸を 1 つずつ振って確かめること。
inline constexpr int SERVO_SIGN[2][2] = {
  {-1, +1},   // 左脚
  {+1, -1},   // 右脚
};

// n_i : ギア比（サーボ 1 回転あたりクランク何回転か）。直結なら 1。
inline constexpr double GEAR_RATIO[2] = {1.0, 1.0};

// ---------------------------------------------------------------------------
// 設計可動域                                                          [deg]
// ---------------------------------------------------------------------------
// ankle_selftest §8.3 の走査より、到達可能領域は原点を中心とする菱形。
//   同時 ±15° … 死点余裕 Δ_min = 200/324（6 割残る）  ← 歩行の設計可動域はここ
//   同時 ±20° … Δ_min = 107/324（3 割）
//   同時 ±25° … 到達不能な点が出る
inline constexpr double TH5_LIMIT_DEG[2] = {-15.0, 15.0};   //!< ピッチ
inline constexpr double TH6_LIMIT_DEG[2] = {-15.0, 15.0};   //!< ロール

// 単軸だけ振ったときの機構上の限界（ロッドが届く範囲、Δ >= 0）。
//   θ6（ロール）  ±41.1°        … 機構で決まる。これ以上は Δ < 0
//   θ5（ピッチ）  -65.8° / +130° … つま先を下げる側はロッドで止まるが、上げる側は
//                                  ロッドでは止まらず、先に下の「型 2 特異点」に入る。
inline constexpr double TH6_MECH_LIMIT_DEG = 41.1;
inline constexpr double TH5_MECH_LIMIT_DEG[2] = {-65.8, +130.0};

// ---------------------------------------------------------------------------
// 型 2 特異点（ピッチを振りすぎたときの発散の正体）
// ---------------------------------------------------------------------------
// 純ピッチ（θ6 = 0）で θ5 を振ると det Jθ = 0 になる点がある（実測）。
//
//     θ5 = +88.0°   つま先を上げる側   このとき Δ ≈ 210 mm²（ロッドは届いている）
//     θ5 = -85.0°   つま先を下げる側   ただし -65.8° でロッドが先に届かなくなる
//
// 値は ℓ5 = leg_config::L5 に依る（ankle_selftest が実測して照合する）。
//
// +88° の側は Δ が正のままなので **逆変換は最後まで普通に解ける**。破綻するのは
// 順変換のほうで、ここで姿勢が飛ぶ。ロッドが届かない（Δ < 0）のとは別の現象なので、
// Δ の監視だけでは検出できない。
//
// ★これは (q1, q2) 平面の中の**曲線**であって箱ではない。サーボの角度リミットは
//   軸ごとの箱しか作れないので、**リミットだけでは特異点に入るのを防げない**。
//   だから防ぐのはソフト側の仕事で、
//     指令側: ankleClampJoints() で θ5 を TH5_ENVELOPE_DEG に丸める
//     観測側: ankleFk() が θ6 を窓の中だけで解き、θ5 は閉形式で出す（下）
//   の 2 か所で受ける。
inline constexpr double TH5_SINGULAR_DEG[2] = {-85.0, +88.0};

// 指令側のピッチのエンベロープ。特異点 +88° と機構限界 -65.8° の内側に取る。
// Δ = 0 の縁は逆変換の精度が落ちるので、機構限界にも 10° の余裕を残してある。
inline constexpr double TH5_ENVELOPE_DEG[2] = {-55.0, +55.0};

// ---------------------------------------------------------------------------
// 順変換を解く窓（θ6 = ロール）                                          [deg]
// ---------------------------------------------------------------------------
// ankleFk() は θ6 を 1 変数にして、この窓の中だけで Φ(θ6) = 0 を解く
// （θ5 は θ6 を固定すれば鎖ごとに閉形式で出る）。窓を置く理由は
//
//   **クランク箱 ±60°（CRANK_LIMIT_DEG）の全域で、この窓の中の Φ の根は高々 1 個**
//
// であることを確かめてあるから（ankle_selftest [S2]。2026-09-14、±75° の箱でも同じ）。
// 根が 1 個なら両端の符号で挟み込め、
//
//   * 二分法で必ず収束する（ニュートンが飛んでも窓から出られない）
//   * 出力は必ず窓の中 ⇒ 姿勢が暴れない
//   * 根が窓から出るときは端に連続に近づくので、張り付け（Clamped）も連続
//
// が全部成り立つ。ロールは ±41° でロッドが届かなくなるので、窓はその 1° 内側。
//
// ★曲線 Θ_i(θ6) が存在する θ6 の区間は (q1, q2) に依り、窓の全幅には及ばない
//   ことがある（ピッチが大きいほどロールの届く幅が狭い）。そこで ankleFk() は窓を
//   FK_SCAN_SAMPLES 点で走査して曲線のある区間と符号の変わる場所を探し、その中で
//   二分法で守ったニュートンを回す。根が無ければ |Φ| が最小になる区間の端に
//   張り付ける（Clamped）。箱の隅（両クランクを同じ向きに振り切った姿勢）が
//   これに当たる。設計可動域 ±15° の 2.7 倍ある。
inline constexpr double FK_WINDOW_DEG[2] = {-40.0, +40.0};

// ---------------------------------------------------------------------------
// クランク角のリミット                                                  [deg]
// ---------------------------------------------------------------------------
// feetech_servo/config/servo_limits.yaml の EEPROM 角度リミットと対で持つ。
// 左右で同じ値でよい（鏡像に映してもクランク角は変わらない。§8 の対称性）。
// サーボ角への読み替えは σ_i・n_i を通す ankleServoFromCrank()。
//
// [-42°, +60°] の根拠（2026-09-14 実装で取り直し。両クランクとも同じ向きに回すと
// ピッチで、- 側がつま先を上げる向き）:
//   * 単軸ピッチ θ5 = -55° / +55°（エンベロープの端）に必要なのが q ≈ +58° / -39°
//   * 単軸ロール θ6 = ±28° まで入る（±30° には q ≈ ±50° が要るので少し足りない）
//   * 設計可動域（同時 ±15° の菱形）は q ∈ [-36°, +39°] で余裕を持って収まる
//   * - 側を -42° で止めるのは**型 2 特異点（純ピッチ +88°）から離すため**。
//     両クランクを -45° より先まで同じ向きに振ると、順変換が特異点の近くで
//     不連続になる（ankle_selftest [S4]）。-42° なら箱の隅でもピッチ +69° に留まり、
//     箱の全域で順変換が連続・有界（Clamped も出ない）。
//   * + 側は特異点から遠く、ロッドが届かなくなる側なので +60° のまま
inline constexpr double CRANK_LIMIT_DEG[2][2] = {
  {-42.0, +60.0},   // 鎖 1（下側・ID6）
  {-42.0, +60.0},   // 鎖 2（上側・ID5）
};

// ---------------------------------------------------------------------------
// ソルバの設定
// ---------------------------------------------------------------------------
// 順変換の 1 変数ソルバ（仕様 §5.2 + 二分法による保護）。初期値は前周期の θ6。
// 上限に達しても窓の外には出ないので、反復数は「精度」だけを決める。
// 二分法だけで進んだ最悪でも 110° / 2^40 まで詰まる。実際はニュートンが効いて
// 3〜5 回で落ちる。
inline constexpr int FK_MAX_ITER = 40;
inline constexpr double FK_TOL_RAD = 1e-12;
inline constexpr double FK_TOL_X_RAD = 1e-13;  //!< ブラケット幅での打ち切り
inline constexpr double FK_DERIV_H = 1e-7;     //!< 数値微分の刻み（仕様 §5.2）

// 窓の走査点数（両端を含む。41 点 = 2° 刻み）と、走査で「根」と認める符号変化の
// 大きさの上限 [rad]。Φ = wrap(Θ1 - Θ2) は ±π で飛ぶので、符号が変わっても差が
// 大きい所は根ではなく折り返し。回数は固定なので最悪実行時間は一定。
inline constexpr int FK_SCAN_SAMPLES = 41;
inline constexpr double FK_WRAP_JUMP_RAD = 1.0;
// 曲線の端（走査で有る/無いが切り替わる所）を詰める二分法の回数
inline constexpr int FK_EDGE_BISECT = 24;

// 警告しきい値。Δ は最大 r² = 324 mm²（仕様 §4.3）。
inline constexpr double DEAD_POINT_MARGIN_MM2 = 10.0;
inline constexpr double SINGULARITY_DET_MIN = 1.0e3;

}  // namespace roboone_kinematics::ankle_config

#endif  // ROBOONE_KINEMATICS__ANKLE_CONFIG_HPP_
