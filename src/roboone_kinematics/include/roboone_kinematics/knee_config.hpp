// 膝 4 節リンク（サーボ角 <-> 膝関節角）の寸法・枝・原点。
//
// knee_fourbar.hpp が読む値はこのファイルにだけ置く。
// CAD や実機の原点出しが変わったらここだけを書き換えれば knee_fourbar.hpp には
// 手を入れなくてよい。leg_config.hpp / ankle_config.hpp と同じ約束。
//
// 単位は長さ mm、角度 deg（内部では rad に直す）。
// 記号は docs/膝4節リンク導出.pdf (KN-1)〜(KN-11) に対応する。同文書は大腿座標系
// Σ_t の点 (O, P0, Q0) からリンク長を作る書き方だが、ここでは膝軸を原点・モータ軸を
// +x 上に置いた「絶対角」の形で持つ。両者は原点と基準角のずれだけの違いで、
// そのずれは THETA4_ZERO_DEG と SERVO_ZERO_DEG が吸収する。対応は
//
//   R1 = g（地節）, R2 = a（クランク）, R3 = b（カプラ）, R4 = c（ロッカー）
//   θ2 = q4 + 定数,  θ4 = ψ = ψ0 + θ4_doc
//
// ===========================================================================
// 座標系（矢状面。膝軸 J4 まわりの回転面をそのまま 2 次元で見る）
// ===========================================================================
//   O4 = (0, 0)                     膝軸。原点
//   O2 = (R1, 0)                    モータ軸
//   A  = O2 + R2·(cos θ2, sin θ2)   クランク先端のピン
//   B  = O4 + R4·(cos θ4, sin θ4)   ロッカー側のピン
//   拘束は |B − A| = R3 の 1 本だけ。角はすべて +x から反時計回り。
//
// この平面は Σ_B に埋め込まなくてよい。脚 IK と繋がるのは「ロッカー角 θ4 と
// 膝関節角の関係」だけで、それは THETA4_ZERO_DEG と SIGMA_JOINT の 2 つに
// 集約されているため（leg_servo.hpp を参照）。
//
// 左右の脚は、この平面内の寸法が共通で、膝軸方向のオフセットだけが鏡像になる。
// したがって平面内の式は左右共通に書ける（文書 §11）。
#ifndef ROBOONE_KINEMATICS__KNEE_CONFIG_HPP_
#define ROBOONE_KINEMATICS__KNEE_CONFIG_HPP_

namespace roboone_kinematics::kconfig
{

// ---------------------------------------------------------------------------
// リンク長                                                             [mm]
// ---------------------------------------------------------------------------
inline constexpr double R1 = 20.0;   // 地節（大腿）  O4 -> O2
inline constexpr double R2 = 45.0;   // クランク（入力・モータ）
inline constexpr double R3 = 35.0;   // カプラ（連結ロッド）
inline constexpr double R4 = 20.0;   // ロッカー（出力・膝ジョイント側のレバー）

// ---------------------------------------------------------------------------
// 枝（円と円の 2 交点のどちらに組んであるか）
// ---------------------------------------------------------------------------
// BETA は順変換 (KN-5)、EPS は逆変換 (KN-7) の arccos に付く符号。
// **機体を組んだ時点で決まる定数**で、動作中に切り替わることはない。
// 本機の寸法は作動域に死点が無い（arccos の引数の最大が 0.812）ので、
// 姿勢ごとに選び直す必要もない。
//
// **左右とも実機確認済み（2026-08-28）**。roboone_motion/viz/serve_knee3d.py で膝を
// 手で曲げ、3D 表示が実機に追従することを左右それぞれ目視で確認した。
// 既存 MATLAB 実装と同じ側。
//
// 左右で同じ値なので配列にしていない（枝は組み方で決まるが、左右同じ組み方だった）。
// 左右で違ったのはサーボの回転方向 SERVO_SIGN だけ。
inline constexpr int BETA = -1;
inline constexpr int EPS = +1;

// ---------------------------------------------------------------------------
// 膝関節角 <-> ロッカー角
// ---------------------------------------------------------------------------
//     θ4_rocker = SIGMA_JOINT · bend + THETA4_ZERO
//
// bend は「膝の曲げ量」（伸展 0・屈曲 +）で、leg_config.hpp の JOINT_LIMIT
// [KNEE] = 0..150 deg と同じ量。脚 IK の公開角 θ4 との読み替えは
// leg_servo.hpp の kneeBendFromLegAngle() 1 か所に閉じ込めてある。

//! 脚が伸び切った姿勢（T ポーズ）でのロッカー角。**確定値**。
inline constexpr double THETA4_ZERO_DEG = 89.3;

//! 膝の曲がる向き ±1。
//!
//! **BETA/EPS と THETA4_ZERO_DEG から一意に決まるので選択の余地がない。**
//! σ = -1 は屈曲 60.3 deg（θ4 = 28.96 deg）で死点に当たり、そこで伝達比が
//! 0.03 まで落ちてサーボが膝を動かせなくなる。設計可動域 0-150 deg に届くのは
//! +1 だけで、knee_selftest がこの一意性を毎回検算する。
inline constexpr int SIGMA_JOINT = +1;

// ---------------------------------------------------------------------------
// サーボ指令への換算（文書 §4.2 式 (4)）    φ4 = φ40 + σ4 n4 θ2
// ---------------------------------------------------------------------------
// **左右で別々に持つ。** 膝サーボは左右とも ID 4 で、どちらのバスに繋がっているかが
// 左右を決める（/dev/feetech_left の ID4 = 左膝、/dev/feetech_right の ID4 = 右膝）。
// 4 節リンクの幾何そのもの（R1-R4, BETA, EPS, THETA4_ZERO_DEG, SIGMA_JOINT）は左右
// 共通だが、**サーボの原点は取り付けごとの実測値なので左右で違う**。実際
// feetech_servo/config/servo_home.yaml の ID4 は左 2095 / 右 1835 で 22.85 deg ずれる。
// σ_m も鏡像取り付けなら左右で反転しうるので、同じく左右別に持つ。
//
// 並びは {RIGHT, LEFT}（Side enum と同じ順）。ankle_config.hpp の鎖ごとの配列と同じ流儀。
//
// SERVO_ZERO_DEG : クランクが θ2 = 0 を向くときのサーボ指令角。実機の原点出しの結果。
// SERVO_SIGN     : サーボの回転方向。θ2 と逆向きなら -1。
// GEAR_RATIO     : ギア比（サーボ 1 回転あたりクランク何回転か）。直結なら 1。
//
// SERVO_SIGN: **左右とも実機確認済み（2026-08-28）**。右 -1 / 左 +1。
//             右脚は ID4 の回転方向が左と逆に組まれている（左右で鏡像になる取り付け）。
//             **左右で違うのはこれだけ**で、枝 BETA/EPS も THETA4_ZERO_DEG も左右共通。
// GEAR_RATIO: 直結とみなした暫定値。実機で振り幅が合わなければ見直す。
// SERVO_ZERO_DEG: 伸び切りのサーボ生カウント（servo_home.yaml の ID4）から作るのが本筋で、
//                 ここは home 以外で原点を決めたいときの上書き用。

//! 膝サーボの ID。左右とも同じで、バスが左右を決める。
inline constexpr int SERVO_ID = 4;

inline constexpr double SERVO_ZERO_DEG[2] = {0.0, 0.0};
inline constexpr int SERVO_SIGN[2] = {-1, +1};   // {RIGHT, LEFT}
inline constexpr double GEAR_RATIO[2] = {1.0, 1.0};

// ---------------------------------------------------------------------------
// 検算・作図で使う範囲                                                 [deg]
// ---------------------------------------------------------------------------
//! 組める θ2 の範囲は [70.5288, 289.4712]（cos θ2 <= 1/3）。その内側を掃く。
inline constexpr double SWEEP_LO_DEG = 160.0;
inline constexpr double SWEEP_HI_DEG = 270.0;

}  // namespace roboone_kinematics::kconfig

#endif  // ROBOONE_KINEMATICS__KNEE_CONFIG_HPP_
